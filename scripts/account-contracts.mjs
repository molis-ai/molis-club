// Derive compile-time types from the pinned runtime contract; never edit generated types.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const base = new URL('../lib/account/contracts/', import.meta.url);
const read = (name) => JSON.parse(readFileSync(new URL(name, base), 'utf8'));
const schema = read('schemas.json'),
  openapi = read('openapi.json');
const snapshot = read('snapshot.json');
for (const [name, expected] of Object.entries(snapshot.files)) {
  const actual = createHash('sha256')
    .update(readFileSync(new URL(name, base)))
    .digest('hex');
  if (actual !== expected)
    throw new Error(`Pinned Auth contract changed: ${name}`);
}
function type(s) {
  if (s.$ref) {
    const name = s.$ref.split('/').at(-1),
      target = schema.$defs[name];
    return target &&
      !target.enum &&
      !('const' in target) &&
      ['string', 'number', 'integer', 'boolean'].includes(target.type)
      ? target.type === 'integer'
        ? 'number'
        : target.type
      : name;
  }
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(JSON.stringify).join(' | ');
  if (s.oneOf)
    return [...new Set(s.oneOf.map((x) => `(${type(x)})`))].join(' | ');
  if (s.anyOf && !s.type)
    return [...new Set(s.anyOf.map((x) => `(${type(x)})`))].join(' | ');
  if (s.allOf && !s.type) return s.allOf.map((x) => `(${type(x)})`).join(' & ');
  if (s.type === 'object') {
    const fields = Object.entries(s.properties ?? {}).map(
      ([k, v]) =>
        `${JSON.stringify(k)}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`,
    );
    if (s.additionalProperties && typeof s.additionalProperties === 'object')
      fields.push(`[key: string]: ${type(s.additionalProperties)}`);
    return fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, never>';
  }
  if (s.type === 'array') return `(${type(s.items)})[]`;
  if (['integer', 'number'].includes(s.type)) return 'number';
  if (['string', 'boolean', 'null'].includes(s.type)) return s.type;
  return 'unknown';
}
const lines = [
  `// Generated by scripts/account-contracts.mjs from the pinned Auth ${snapshot.contractVersion} contract.`,
];
for (const [name, def] of Object.entries(schema.$defs))
  lines.push(`export type ${name} = ${type(def)};`);
lines.push('export interface CentralOperations {');
for (const [path, methods] of Object.entries(openapi.paths)) {
  if (!path.startsWith('/api/v2/')) continue;
  for (const op of Object.values(methods)) {
    const body = op.requestBody?.content['application/json'].schema;
    const output = op.responses['200'].content['application/json'].schema;
    lines.push(
      `${JSON.stringify(op.operationId)}: { body: ${body ? type(body) : 'undefined'}; output: ${type(output)} };`,
    );
  }
}
lines.push(
  '}',
  'export type CentralOperationId = keyof CentralOperations;',
  '',
);
const generated = lines.join('\n');
const file = new URL('types.ts', base);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== generated)
    throw new Error('Account contract types are stale');
} else writeFileSync(file, generated);
